clc; clear; close all;

output_folder = 'EV_Battery_Outputs';
if ~exist(output_folder,'dir'), mkdir(output_folder); end

fprintf('==========================================\n');
fprintf('   MODULE 13: FINAL CSV REPORT EXPORT     \n');
fprintf('==========================================\n\n');

load('normal_condition.mat');
t=t_normal; V=V_normal; I=I_normal; SOC=SOC_normal;
Q_pack=20;

%% --- GENERATE ALL DERIVED SIGNALS ---
dV       = gradient(V);
dI       = gradient(I);
P        = V.*I;
E_cum    = cumtrapz(t,P)/3600;   % Wh
R_approx = V./(abs(I)+1e-6);

% Fault signals
V_fault  = V; V_fault(t>=1800) = V_fault(t>=1800) - 0.15;
I_fault  = I; I_fault(t>=2200&t<=2400)=I_fault(t>=2200&t<=2400)*3.5;
SOC_fault= SOC; SOC_fault(t>=2500)=SOC_fault(t>=2500)-0.08;

% Fault flags
flag_V   = double(V_fault < 3.90);
flag_I   = double(I_fault > 1.5);
flag_SOC = double(SOC_fault < 0.20);
flag_any = double(flag_V|flag_I|flag_SOC);

% SOH
V_mx=4.2; V_mn=3.0;
SOH_n=(mean(V)-V_mn)/(V_mx-V_mn)*100;
SOH_f=(mean(V_fault)-V_mn)/(V_mx-V_mn)*100;
SOH_arr=ones(length(t),1)*SOH_n;
SOH_arr_f=ones(length(t),1)*SOH_f;

% Coulomb counting SOC
SOC_cc=zeros(length(t),1); SOC_cc(1)=1.0;
for k=2:length(t)
    SOC_cc(k)=max(SOC_cc(k-1)-abs(I(k))/(Q_pack*3600),0);
end

%% --- BUILD TABLE ---
T_report = table(...
    t,...
    V,...
    V_fault,...
    I,...
    I_fault,...
    SOC*100,...
    SOC_fault*100,...
    SOC_cc*100,...
    dV,...
    dI,...
    P,...
    E_cum,...
    R_approx,...
    flag_V,...
    flag_I,...
    flag_SOC,...
    flag_any,...
    SOH_arr,...
    SOH_arr_f,...
    'VariableNames',{...
    'Time_s',...
    'Voltage_Normal_V',...
    'Voltage_Fault_V',...
    'Current_Normal_A',...
    'Current_Fault_A',...
    'SOC_Kalman_pct',...
    'SOC_Fault_pct',...
    'SOC_Coulomb_pct',...
    'dVdt',...
    'dIdt',...
    'Power_W',...
    'Energy_Cum_Wh',...
    'Resistance_approx_Ohm',...
    'Flag_Voltage_Fault',...
    'Flag_Current_Fault',...
    'Flag_SOC_Fault',...
    'Flag_Any_Fault',...
    'SOH_Normal_pct',...
    'SOH_Fault_pct'});

%% --- EXPORT ---
csv_path = fullfile(output_folder,'M13_Final_Battery_Report.csv');
writetable(T_report, csv_path);

fprintf('Report contains %d rows x %d columns\n',...
    height(T_report), width(T_report));
fprintf('\nColumns exported:\n');
fprintf('  Time_s, Voltage_Normal_V, Voltage_Fault_V\n');
fprintf('  Current_Normal_A, Current_Fault_A\n');
fprintf('  SOC_Kalman_pct, SOC_Fault_pct, SOC_Coulomb_pct\n');
fprintf('  dVdt, dIdt, Power_W, Energy_Cum_Wh\n');
fprintf('  Resistance_approx_Ohm\n');
fprintf('  Flag_Voltage_Fault, Flag_Current_Fault\n');
fprintf('  Flag_SOC_Fault, Flag_Any_Fault\n');
fprintf('  SOH_Normal_pct, SOH_Fault_pct\n');

fprintf('\n=== SUMMARY STATISTICS ===\n');
fprintf('Duration         : %.0f s\n', t(end));
fprintf('Initial Voltage  : %.4f V\n', V(1));
fprintf('Final Voltage    : %.4f V\n', V(end));
fprintf('Initial SOC      : %.2f%%\n', SOC(1)*100);
fprintf('Final SOC        : %.2f%%\n', SOC(end)*100);
fprintf('SOH Normal       : %.2f%%\n', SOH_n);
fprintf('SOH Fault        : %.2f%%\n', SOH_f);
fprintf('Total Faults     : %d time steps\n', sum(flag_any));
fprintf('Fault Percentage : %.2f%% of runtime\n',...
    sum(flag_any)/length(t)*100);
fprintf('==========================\n');

fprintf('\n✔ Saved: M13_Final_Battery_Report.csv\n');
fprintf('MODULE 13 COMPLETE!\n');
